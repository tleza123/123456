        var existing = existingDoc.data() || {};
        var previous = Array.isArray(existing.slips) ? existing.slips : [];
        if (!previous.length && Array.isArray(existing.slipUrls)) previous = existing.slipUrls.map(function(url) { return { imageUrl: url, fileUrl: url, transferDateTime: existing.transferDateTime || '' }; });
