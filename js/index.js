  async function processSlipUploadQueue() {
    if (isProcessingSlipQueue) return;
    isProcessingSlipQueue = true;

    try {
      for (var i = 0; i < uploadedSlips.length; i++) {
        var item = uploadedSlips[i];
        if (item.status === 'uploading' && !item.inProgress) {
          item.inProgress = true;
          renderSlipsList();
          updateUploadButtonState();
          await uploadSingleSlip(item);
          item.inProgress = false;
          renderSlipsList();
          updateUploadButtonState();
        }
      }
    } finally {
      isProcessingSlipQueue = false;
      if (uploadedSlips.some(function(slip) { return slip.status === 'uploading' && !slip.inProgress; })) processSlipUploadQueue();
    }
  }

  async function uploadSingleSlip(item) {
    var identity = currentStudentId;
    try {
      var compressed = await DE06.compress(item.file);
      if (identity !== currentStudentId || !uploadedSlips.includes(item)) return;
      var result = await callAPI('preUploadImage', {
        studentId: identity, base64Data: compressed.dataUrl.split(',')[1],
        fileName: item.fileName.replace(/\.[^.]+$/, '') + '.jpg', mimeType: compressed.mimeType
      });
      if (identity !== currentStudentId || !uploadedSlips.includes(item)) return;
      item.imageUrl = DE06.safeUrl(result.imageUrl || result.fileUrl, true);
      item.fileUrl = DE06.safeUrl(result.fileUrl || result.imageUrl, true);
      if (!item.imageUrl && !item.fileUrl) throw new Error('ปลายทางไม่ได้ส่งข้อมูลรูปภาพกลับมา');
      item.width = compressed.width; item.height = compressed.height; item.status = 'done'; item.error = '';
    } catch (error) { item.status = 'error'; item.error = error.message || 'อัปโหลดภาพไม่สำเร็จ'; }
    syncLegacySlipUrls();
  }

  function syncLegacySlipUrls() {
    var firstDone = uploadedSlips.find(function(s) { return s.status === 'done'; });
    if (firstDone) {
      preUploadedImageUrl = firstDone.imageUrl;
      preUploadedFileUrl = firstDone.fileUrl;
    } else {
      preUploadedImageUrl = '';
      preUploadedFileUrl = '';
    }
  }

  function removeSlip(id) {
    var idx = uploadedSlips.findIndex(function(s) { return s.id === id; });
    if (idx !== -1) {
      var item = uploadedSlips[idx];
      if (item.previewUrl) {
        try { URL.revokeObjectURL(item.previewUrl); } catch (e) {}
      }
      uploadedSlips.splice(idx, 1);
      syncLegacySlipUrls();
      syncLegacyDateTimeInputs();
      renderSlipsList();
      updateUploadButtonState();
    }
  }

  function retrySlip(id) {
    var item = uploadedSlips.find(function(s) { return s.id === id; });
    if (item) {
      item.status = 'uploading';
      item.error = '';
      item.inProgress = false;
      renderSlipsList();
      updateUploadButtonState();
      processSlipUploadQueue();
    }
  }

