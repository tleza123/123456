  async function readUsageHistory() {
    if (!currentStudentId) return;
    var studentId = currentStudentId;
    var request = ++usageHistory.request;
    usageHistory.rows = [];
    usageHistory.visible = 20;
    var container = document.getElementById('booking-details-content');
    var status = document.getElementById('history-status');
    status.textContent = 'กำลังโหลดประวัติการใช้งาน';
    container.setAttribute('aria-busy', 'true');
    container.innerHTML = '<div class="history-list" aria-hidden="true">' + Array.from({ length: 3 }, function() { return '<div class="history-card"><div class="skeleton-line"></div><div class="skeleton-line"></div><div class="skeleton-line"></div></div>'; }).join('') + '</div>';
    var sources = ['bookings', 'orders_shirts', 'votes', 'comments', 'dynamic_submissions', 'inquiries'];
    var results = await Promise.allSettled(sources.map(function(source) {
      if (source === 'bookings') return db.collection(source).doc(studentId).get();
      var query = db.collection(source).where('studentId', '==', studentId);
      return typeof DE06 !== 'undefined' ? DE06.allDocuments(query) : query.get();
    }));
    if (request !== usageHistory.request || currentStudentId !== studentId) return;
    var rows = [];
    var votes = new Map();
    var failures = [];
    results.forEach(function(result, index) {
      var source = sources[index];
      if (result.status !== 'fulfilled') { failures.push(source); return; }
      function collect(doc) {
        var data = doc.data();
        if (data.studentId && data.studentId !== studentId) return;
        var row = source === 'bookings' || source === 'orders_shirts' ? historyBooking(data, source) : historySubmission(data, source);
        if (row.type === 'vote') {
          var key = data.activityId || doc.id;
          if (!votes.has(key) || votes.get(key).time < row.time) votes.set(key, row);
        } else rows.push(row);
      }
      if (source === 'bookings') { if (result.value.exists) collect(result.value); }
      else result.value.forEach(collect);
    });
    votes.forEach(function(row) { rows.push(row); });
    usageHistory.studentId = studentId;
    usageHistory.loadedAt = failures.length ? 0 : Date.now();
    usageHistory.rows = rows.sort(function(a, b) { return b.time - a.time; });
    container.setAttribute('aria-busy', 'false');
    renderUsageHistory();
    var cachedOnly = results.some(function(result) { return result.status === 'fulfilled' && (result.value.fromCache || (result.value.metadata && result.value.metadata.fromCache)); });
    status.textContent = failures.length ? 'โหลดประวัติบางส่วนไม่สำเร็จ กรุณาลองใหม่' : cachedOnly ? 'แสดงประวัติที่บันทึกไว้ ข้อมูลล่าสุดอาจไม่ครบ' : 'ประวัติ ' + rows.length + ' รายการ';
    if (failures.length && !rows.length) container.innerHTML = '';
  }


